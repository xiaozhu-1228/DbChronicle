using System.Linq;

using DbChronicle.Common.Enums;

using Xunit;

namespace DbChronicle.Tests
{
    public class CapabilityGuardTests
    {
        private const string CreateWithUniqueColumn =
            "  <table name=\"t1\" action=\"CREATE\">\n"
            + "    <column name=\"id\" action=\"ADD\" type=\"Int64\" primaryKey=\"true\" nullable=\"false\"/>\n"
            + "    <column name=\"code\" action=\"ADD\" type=\"String\" length=\"16\" nullable=\"true\" unique=\"true\"/>\n"
            + "  </table>";

        private const string ModifyUniqueColumn =
            "  <table name=\"t1\" action=\"ALTER\">\n"
            + "    <column name=\"code\" action=\"MODIFY\" type=\"String\" length=\"16\" nullable=\"true\" unique=\"true\"/>\n"
            + "  </table>";

        private const string ModifyAutoIncrement =
            "  <table name=\"t1\" action=\"ALTER\">\n"
            + "    <column name=\"id\" action=\"MODIFY\" type=\"Int64\" nullable=\"false\" autoIncrement=\"true\"/>\n"
            + "  </table>";

        private const string EmptyRawSql =
            "  <rawSql name=\"t1\"><sql dialect=\"any\"></sql></rawSql>";

        private const string EmptyTrigger =
            "  <trigger name=\"trg_t1\"><sql dialect=\"any\">   </sql></trigger>";

        private const string EmptySequenceSql =
            "  <sequence name=\"seq_t1\"><sql dialect=\"any\"></sql></sequence>";

        private const string StageBefore =
            "  <rawSql name=\"t1\" stage=\"before\"><![CDATA[SELECT 'BEFORE_MARKER']]></rawSql>\n"
            + "  <table name=\"t1\" action=\"CREATE\">\n"
            + "    <column name=\"id\" action=\"ADD\" type=\"Int64\" primaryKey=\"true\" nullable=\"false\"/>\n"
            + "  </table>";

        private const string StageDefault =
            "  <table name=\"t1\" action=\"CREATE\">\n"
            + "    <column name=\"id\" action=\"ADD\" type=\"Int64\" primaryKey=\"true\" nullable=\"false\"/>\n"
            + "  </table>\n"
            + "  <rawSql name=\"t1\"><![CDATA[SELECT 'AFTER_MARKER']]></rawSql>";

        [Theory]
        [InlineData("mysql")]
        [InlineData("postgresql")]
        [InlineData("sqlite")]
        [InlineData("sqlserver")]
        public void ColumnUnique_ShouldEmitUniqueConstraint(string dialect)
        {
            var result = TestSupport.CompileWith(dialect, TestSupport.ParseSingle(CreateWithUniqueColumn, false), false, null);

            Assert.False(result.HasErrors);
            Assert.Contains("UNIQUE", result.Sql);
        }

        [Fact]
        public void PostgreSql_ModifyUnique_ShouldAddNamedConstraint()
        {
            var result = TestSupport.CompileWith("postgresql", TestSupport.ParseSingle(ModifyUniqueColumn, false), false, null);

            Assert.Contains("ADD CONSTRAINT \"uk_t1_code\" UNIQUE (\"code\")", result.Sql);
        }

        [Fact]
        public void MySql_ModifyUnique_ShouldEmitInlineUnique()
        {
            var result = TestSupport.CompileWith("mysql", TestSupport.ParseSingle(ModifyUniqueColumn, false), false, null);

            Assert.Contains("UNIQUE", result.Sql);
            Assert.False(result.HasErrors);
        }

        [Fact]
        public void PostgreSql_ModifyAutoIncrement_ShouldErrorE052()
        {
            var result = TestSupport.CompileWith("postgresql", TestSupport.ParseSingle(ModifyAutoIncrement, false), false, null);

            Assert.True(result.HasErrors);
            Assert.Contains(result.Diagnostics, x => x.Code == "E052" && x.Severity == DiagnosticSeverity.Error);
            Assert.DoesNotContain("GENERATED BY", result.Sql);
        }

        [Fact]
        public void MySql_ModifyAutoIncrement_ShouldStillWork()
        {
            var result = TestSupport.CompileWith("mysql", TestSupport.ParseSingle(ModifyAutoIncrement, false), false, null);

            Assert.False(result.HasErrors);
            Assert.Contains("AUTO_INCREMENT", result.Sql);
        }

        [Theory]
        [InlineData(EmptyRawSql)]
        [InlineData(EmptyTrigger)]
        [InlineData(EmptySequenceSql)]
        public void EmptySqlNode_ShouldErrorE051(string body)
        {
            var unit = TestSupport.ParseSingle(body, false);

            Assert.Contains(unit.Diagnostics, x => x.Code == "E051" && x.Severity == DiagnosticSeverity.Error);
        }

        [Fact]
        public void RawSql_WithStageBefore_ShouldSortBeforeCreateTable()
        {
            var result = TestSupport.CompileWith("mysql", TestSupport.ParseSingle(StageBefore, false), false, null);

            var marker = result.Sql.IndexOf("BEFORE_MARKER");
            var create = result.Sql.IndexOf("CREATE TABLE");

            Assert.True(marker >= 0 && create >= 0 && marker < create,
                "before 的 rawSql 应排在 CREATE TABLE 之前：" + result.Sql);
        }

        [Fact]
        public void RawSql_WithoutStage_ShouldStayAfterStructureChange()
        {
            var result = TestSupport.CompileWith("mysql", TestSupport.ParseSingle(StageDefault, false), false, null);

            var marker = result.Sql.IndexOf("AFTER_MARKER");
            var create = result.Sql.IndexOf("CREATE TABLE");

            Assert.True(marker >= 0 && create >= 0 && create < marker,
                "缺省（after）的 rawSql 应排在 CREATE TABLE 之后：" + result.Sql);
        }

        [Fact]
        public void ModifyWithoutDefault_ShouldNotWarnW008_InFullMode()
        {
            var result = TestSupport.CompileWith("mysql", TestSupport.ParseSingle(ModifyAutoIncrement, false), false, null);

            Assert.DoesNotContain(result.Diagnostics, x => x.Code == "W008");
        }
    }
}
